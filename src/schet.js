/*
 * Счётчик событий.
 *
 * Просмотр страницы считает сам umami. Здесь — то, чего он не знает: игру
 * не «прочитывают», из неё уходят в четырёх разных местах, и это разные
 * вещи. Ушёл из меню, не начав; бросил первый бой; проиграл; выиграл.
 *
 * Три требования, каждое проверяемое:
 *
 * 1. **Молча глохнуть.** Счётчика может не быть — блокировщик, localhost,
 *    отложенная загрузка. Уронить кадр из-за него нельзя.
 * 2. **Ничего про человека.** Только числа: попытка, здоровье, комбо,
 *    сколько костей. Ни имён, ни зерна боя — зерно позволяет повторить
 *    чужую партию, а это уже про конкретного игрока.
 * 3. **Прогоны не оседают в боевых данных.** Немой запуск (`?тихо`) —
 *    признак замера, а не игры: человек звук не выключает параметром в
 *    адресе. Оттуда события не уходят вовсе. Иначе за месяц половина
 *    статистики станет нашей, ровно как у Тестера, нагнавшего сорок
 *    просмотров по живому счётчику.
 */
import { isQuiet } from './audio.js';
import { INTACT } from './body.js';

let попытка = 0;

/** Замер это или живая игра. Считается один раз, при загрузке. */
const замер = (() => {
    try {
        return isQuiet();
    } catch {
        return false;
    }
})();

function послать(имя, числа) {
    if (замер) return;
    try {
        globalThis.umami?.track?.(имя, числа);
    } catch {
        /* Счётчик — не причина ронять игру. */
    }
}

export function бойНачат() {
    попытка += 1;
    послать('бой-начат', { попытка });
}

export function бойКончен(fight) {
    const [ты, он] = fight.fighters;
    const сломано = (боец) => Object.values(боец.body.bones).filter((b) => b.state !== INTACT).length;
    послать(fight.winner === 0 ? 'победа' : 'поражение', {
        попытка,
        комбо: fight.bestJuggle,
        сломалЕму: сломано(он),
        сломалиТебе: сломано(ты),
        здоровье: Math.round(ты.body.hp),
        секунды: Math.round(fight.frame / 60),
    });
}

export function обучениеОткрыто() {
    послать('обучение-открыто', { попытка });
}

/** Для проверок: ушли бы события отсюда наружу. */
export function шлётся() {
    return !замер;
}
