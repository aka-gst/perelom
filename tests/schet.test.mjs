/*
 * Счётчик событий.
 *
 * Проверяется не «вызвана ли функция», а что именно уходит наружу и в
 * каких случаях не уходит вовсе. По правилу владельца прогоны не должны
 * оседать в боевых данных: Тестер уже нагнал сорок просмотров по живому
 * счётчику, и отличить их от людей потом нечем.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

const БОЕЦ = (hp, сломано = []) => ({
    body: {
        hp,
        bones: Object.fromEntries(
            ['arm', 'leg', 'ribs', 'spine', 'skull'].map((id) => [id, { state: сломано.includes(id) ? 'broken' : 'intact' }]),
        ),
    },
});

const БОЙ = (winner) => ({ winner, frame: 1800, bestJuggle: 4, fighters: [БОЕЦ(winner === 0 ? 42 : 0, ['leg']), БОЕЦ(0, ['arm', 'ribs'])] });

/** Загрузить счётчик заново с нужным адресом страницы: замер он или игра. */
async function поднять(адрес) {
    globalThis.location = { search: адрес, href: `http://x/${адрес}` };
    const пойманное = [];
    globalThis.umami = { track: (имя, числа) => пойманное.push({ имя, числа }) };
    const модуль = await import(`../src/schet.js?${encodeURIComponent(адрес)}`);
    return { модуль, пойманное };
}

test('победа и поражение уходят разными именами и несут числа', async () => {
    const { модуль, пойманное } = await поднять('');
    assert.equal(модуль.шлётся(), true, 'обычная игра обязана считаться');
    модуль.бойНачат();
    модуль.бойКончен(БОЙ(0));
    модуль.бойНачат();
    модуль.бойКончен(БОЙ(1));

    assert.deepEqual(пойманное.map((e) => e.имя), ['бой-начат', 'победа', 'бой-начат', 'поражение']);
    assert.equal(пойманное[0].числа.попытка, 1);
    assert.equal(пойманное[2].числа.попытка, 2, 'номер попытки должен расти — иначе не видно, вернулся ли человек');
    assert.deepEqual(пойманное[1].числа, {
        попытка: 1, комбо: 4, сломалЕму: 2, сломалиТебе: 1, здоровье: 42, секунды: 30,
    });
});

test('в события не уходит ничего про человека', async () => {
    const { модуль, пойманное } = await поднять('?a');
    модуль.бойНачат();
    модуль.бойКончен(БОЙ(0));
    модуль.обучениеОткрыто();
    for (const { числа } of пойманное) {
        for (const [ключ, значение] of Object.entries(числа)) {
            assert.equal(typeof значение, 'number', `«${ключ}» — не число, а значит может нести чужое`);
        }
        assert.ok(!('зерно' in числа), 'зерно позволяет повторить чужую партию');
    }
});

test('немой запуск ничего не шлёт — это замер, а не игра', async () => {
    for (const адрес of ['?тихо', '?tiho=1', '?quiet', `?${encodeURIComponent('тихо')}`]) {
        const { модуль, пойманное } = await поднять(адрес);
        assert.equal(модуль.шлётся(), false, `${адрес}: замер принят за игру`);
        модуль.бойНачат();
        модуль.бойКончен(БОЙ(0));
        модуль.обучениеОткрыто();
        assert.deepEqual(пойманное, [], `${адрес}: прогон осел бы в боевых данных`);
    }
});

test('без счётчика на странице игра не падает', async () => {
    const { модуль } = await поднять('?b');
    delete globalThis.umami;
    assert.doesNotThrow(() => { модуль.бойНачат(); модуль.бойКончен(БОЙ(1)); модуль.обучениеОткрыто(); });
});
