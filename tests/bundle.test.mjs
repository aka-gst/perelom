/*
 * Проверка выкладываемого файла, а не исходников.
 *
 * Однофайловая сборка — это то единственное, что видит человек. Исходники
 * могут быть безупречны, а до него доедет другое: сборка вырезает из
 * `index.html` только `<main>`, поэтому всё, что стоит в шапке, теряется
 * молча. Ровно так пропал счётчик — тег в разметке был, в выкладке его не
 * было, и обе половины выглядели сделанными.
 *
 * Поэтому спрашиваем собранный файл, а не тот, куда удобно писать.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readFileSync } from 'node:fs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundle = execFileSync('node', [join(root, 'tools/bundle.mjs')], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
});

test('файл в дереве совпадает со свежей сборкой', () => {
    /*
     * Самая дорогая проверка этого файла, и её тут не было.
     *
     * Все проверки ниже собирают сборку заново и спрашивают её. А наружу
     * едет `perelom.html` из дерева — и он отставал: арт второго бойца
     * приехал в `c815b8a`, а сборку я пересобрать забыл. Соседняя сессия
     * пошла снимать кадр по моему же рецепту и увидела вчерашние палки,
     * при том что арт в дереве был и все проверки были зелёными.
     *
     * То есть проверки смотрели на соседа, а не на предмет: на вывод
     * сборщика вместо файла, который получает человек.
     */
    const вДереве = readFileSync(join(root, 'perelom.html'), 'utf8');
    assert.equal(вДереве.length, bundle.length,
        'perelom.html отстал от исходников — пересобрать: npm run bundle');
    assert.ok(вДереве === bundle,
        'perelom.html расходится со сборкой при том же размере — пересобрать');
});

test('сборка объявляет кодировку до первого русского слова', () => {
    const charset = bundle.indexOf('<meta charset="utf-8">');
    const title = bundle.indexOf('ПЕРЕЛОМ');
    assert.ok(charset >= 0, 'нет объявления кодировки — на чужом сервере текст рассыплется');
    assert.ok(charset < title, 'кодировка объявлена позже русского текста');
});

test('сборка несёт счётчик событий', () => {
    assert.match(bundle, /data-website-id="de024048-c4c3-4639-bbdf-808c558f6d71"/,
        'счётчик потерялся по дороге из index.html в выкладку');
    assert.match(bundle, /src="\/pulse\/script\.js"/,
        'путь к счётчику должен быть от корня сайта: stats.aka-gst.ru снаружи отдаёт 404');
});

test('из сборки можно выйти на главную', () => {
    assert.match(bundle, /class="site-home"/, 'нет кнопки «на главную»');
});

test('всё, что сборка зовёт, в ней же и объявлено', () => {
    /*
     * Слепое пятно, стоившее выкладки сломанной игры.
     *
     * Сборка склеивает модули по списку. Новый `schet.js` в список не
     * попал — и получился файл, зовущий три несуществующие функции.
     * Синтаксис верный, `node --check` доволен, все тесты зелёные: они
     * берут `src/` напрямую и о списке не знают. Упало бы у человека на
     * первом нажатии.
     *
     * Поэтому читаем собранный файл как текст и спрашиваем его самого.
     */
    // Комментарии выкидываем: в них по-русски пишут «поставка (49 файлов)»,
    // и такое неотличимо от вызова.
    const код = bundle
        .slice(bundle.indexOf('<script type="module">'))
        .replace(/\/\*[\s\S]*?\*\//g, ' ')
        .replace(/^\s*\/\/.*$/gm, ' ');

    const объявлено = new Set();
    for (const [, имя] of код.matchAll(/(?:function|const|let|var)\s+([\p{L}\w$]+)/gu)) объявлено.add(имя);
    // Имена, приходящие аргументами, тоже объявлены — просто в скобках.
    for (const [, имя] of код.matchAll(/\(\s*([\p{Script=Cyrillic}][\p{L}\w$]*)\s*[,)]/gu)) объявлено.add(имя);

    // Своими считаем имена с кириллицей: они точно не из браузера.
    const свои = new Set();
    for (const [, имя] of код.matchAll(/([\p{Script=Cyrillic}][\p{L}\w$]*)\s*\(/gu)) свои.add(имя);

    const потерянные = [...свои].filter((имя) => !объявлено.has(имя));
    assert.deepEqual(потерянные, [], `сборка зовёт то, чего в ней нет: ${потерянные.join(', ')}`);
});

test('в сборке есть все модули из `src`, а не только перечисленные', () => {
    const код = bundle.slice(bundle.indexOf('<script type="module">'));
    // Ни один локальный импорт не должен пережить склейку: переживший
    // означает, что модуль не вошёл, и браузер полезет за ним по сети.
    const выжившие = [...код.matchAll(/^\s*import\s[^']*'\.\/([\w-]+)\.js'/gm)].map((m) => m[1]);
    assert.deepEqual(выжившие, [], `модули не вошли в сборку: ${выжившие.join(', ')}`);
});

test('в сборку не уехали рабочие записи', () => {
    for (const след of ['ФИНИШ', 'CLAUDE.md', 'docs/JUGGLE']) {
        assert.ok(!bundle.includes(след), `в выкладке оказалось внутреннее: ${след}`);
    }
});
