/**
 * Сверить бой с деревом.
 *
 *   npm run sverka
 *
 * Вторая половина сторожа. Первая (`tests/bundle.test.mjs`) следит, чтобы
 * `perelom.html` не отстал от исходников, — но сравнивает два файла **у
 * нас**. Разойтись же могут дерево и **сервер**, и тогда всё выглядит
 * исправным: страница отдаёт 200, игра работает, просто это прошлая игра.
 *
 * Так и вышло: перекрасил, пересобрал, а выкладки не было — и на бою
 * лежала сборка на 184 КБ легче, ровно на вес арта второго бойца. Заметили
 * не кодом ответа, а тем, что открыли игру и увидели палки.
 *
 * Поэтому здесь три вопроса подряд, и каждый следующий строже:
 *   1) свежая ли сборка в дереве — иначе сверять нечего;
 *   2) то же ли лежит на бою — побайтно, а не по коду ответа;
 *   3) виден ли с витрины путь на игру — выложено и достижимо разные вещи.
 *
 * Сеть даёт обрывы, поэтому каждый запрос с повторами. Пустой ответ и
 * ответ не тем содержимым различаются: молчание — не ответ.
 */

import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const ИГРА = 'https://aka-gst.ru/perelom/';
const ВИТРИНА = 'https://aka-gst.ru/';
const ПОПЫТОК = 4;

const хеш = (s) => createHash('md5').update(s).digest('hex').slice(0, 12);

async function достать(адрес) {
    let беда = null;
    for (let n = 1; n <= ПОПЫТОК; n += 1) {
        try {
            const ответ = await fetch(адрес, { signal: AbortSignal.timeout(20000) });
            if (!ответ.ok) throw new Error(`код ${ответ.status}`);
            const текст = await ответ.text();
            if (!текст.length) throw new Error('пустой ответ');
            return текст;
        } catch (e) {
            беда = e;
            await new Promise((r) => setTimeout(r, 400 * n));
        }
    }
    throw new Error(`${адрес}: ${беда.message} (после ${ПОПЫТОК} попыток)`);
}

const беды = [];
const ладно = [];

// 1. Свежесть сборки. Без неё второй вопрос бессмысленен.
const вДереве = readFileSync('perelom.html', 'utf8');
const свежая = execFileSync('node', ['tools/bundle.mjs'], { encoding: 'utf8', maxBuffer: 64 << 20 });
if (вДереве === свежая) ладно.push(`сборка в дереве свежая (${хеш(вДереве)}, ${(вДереве.length / 1048576).toFixed(2)} МБ)`);
else беды.push(`сборка в дереве отстала от исходников — «npm run bundle»`);

// 2. То же ли на бою.
const наБою = await достать(ИГРА);
if (наБою === вДереве) {
    ладно.push(`бой совпадает с деревом (${хеш(наБою)})`);
} else {
    const разница = вДереве.length - наБою.length;
    беды.push(
        `на бою другая сборка: ${хеш(наБою)} против ${хеш(вДереве)}, `
        + `${разница > 0 ? 'легче' : 'тяжелее'} на ${Math.abs(разница)} байт. `
        + 'Код ответа этого не покажет — страница честно отдаёт 200.',
    );
}

// 3. Достижимость с витрины: выложено и найдено — разные вещи.
const витрина = await достать(ВИТРИНА);
if (витрина.includes('href="/perelom/"')) ладно.push('с витрины на игру ведёт ссылка');
else беды.push('игра лежит, но с витрины на неё не попасть — карточки нет');

for (const с of ладно) console.log('  ✓', с);
for (const с of беды) console.log('  ✗', с);
console.log();
console.log(беды.length ? `РАСХОЖДЕНИЙ: ${беды.length}` : 'БОЙ СОВПАДАЕТ С ДЕРЕВОМ');
process.exit(беды.length ? 1 : 0);
